    private void btnBuscarProdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarProdActionPerformed
         try {

        int id = Integer.parseInt(txtIdProducto.getText().trim());

        Producto p = gestorInventario.buscarProducto(id);

        if (p == null) {
            JOptionPane.showMessageDialog(this, "Producto no encontrado");
            lblProductoInfo.setText("-");
            return;
        }

        lblProductoInfo.setText(
                p.getMarca() + " " +
                p.getModelo() +
                " | S/. " + p.getPrecio() +
                " | Stock: " + p.getStock()
        );

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Ingrese un ID de producto válido");
    }
    }//GEN-LAST:event_btnBuscarProdActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {

        // Verificar que se haya seleccionado un cliente
        if (lblClienteInfo.getText().equals("—")) {
            JOptionPane.showMessageDialog(this, "Primero busque un cliente.");
            return;
        }

        // Crear la venta si aún no existe
        if (ventaActual == null) {

            String idCliente = txtIdCliente.getText().trim();
            Cliente cliente = gestorCliente.buscarCliente(idCliente);

            if (cliente == null) {
                JOptionPane.showMessageDialog(this, "Cliente no encontrado.");
                return;
            }

            ventaActual = new Venta(
                    gestorVentas.obtenerSiguienteIdVenta(),
                    cliente,
                    usuarioLogueado
            );
        }

        // Buscar producto
        int idProducto = Integer.parseInt(txtIdProducto.getText().trim());

        Producto producto = gestorInventario.buscarProducto(idProducto);

        if (producto == null) {
            JOptionPane.showMessageDialog(this, "Producto no encontrado.");
            return;
        }

        // Leer cantidad
        int cantidad = Integer.parseInt(txtCantidad.getText().trim());

        if (cantidad <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor que cero.");
            return;
        }

        if (cantidad > producto.getStock()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Stock insuficiente. Disponible: " + producto.getStock()
            );
            return;
        }

        // Crear detalle
        DetalleVenta detalle = new DetalleVenta(producto, cantidad);
        ventaActual.agregarDetalle(detalle);

        // Agregar a la tabla
        modelo.addRow(new Object[]{
            producto.getIdProducto(),
            producto.getCodigo(),
            producto.getMarca() + " " + producto.getModelo(),
            String.format("S/. %.2f", producto.getPrecio()),
            cantidad,
            String.format("S/. %.2f", detalle.getSubtotal())
        });

        // Actualizar total
        lblTotal.setText(
                "TOTAL: S/. " +
                String.format("%.2f", ventaActual.getTotal())
        );

        // Limpiar controles
        txtIdProducto.setText("");
        txtCantidad.setText("");
        lblProductoInfo.setText("—");
        txtIdProducto.requestFocus();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
                this,
                "Ingrese valores numéricos válidos."
        );
    }

    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarFilaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarFilaActionPerformed
        int fila = tblDetalle.getSelectedRow();
        if (fila < 0) { JOptionPane.showMessageDialog(this, "Seleccione una fila para eliminar"); return; }
        modelo.removeRow(fila);

    if (ventaActual != null) {
        ventaActual.getDetalles().remove(fila);

        double total = 0;

        for (DetalleVenta d : ventaActual.getDetalles()) {
            total += d.getSubtotal();
        }

        ventaActual.setTotal(total);

        lblTotal.setText("TOTAL: S/. " + String.format("%.2f", total));

        if (ventaActual.getDetalles().isEmpty()) {
            ventaActual = null;
        }
    }
    }//GEN-LAST:event_btnEliminarFilaActionPerformed

    private void btnBuscarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarClienteActionPerformed
        try {
            int id = Integer.parseInt(txtIdCliente.getText().trim());
            Cliente c = gestorCliente.buscarCliente(String.valueOf(id));
            if (c == null) { JOptionPane.showMessageDialog(this, "Cliente no encontrado"); lblClienteInfo.setText("—"); return; }
            lblClienteInfo.setText(c.mostrarDatos());
        } catch (NumberFormatException e) { JOptionPane.showMessageDialog(this, "Ingrese un ID de cliente válido"); }
    }//GEN-LAST:event_btnBuscarClienteActionPerformed

    private void btnNuevaVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNuevaVentaActionPerformed
        if (modelo.getRowCount() > 0) {
            int r = JOptionPane.showConfirmDialog(this, "¿Cancelar la venta actual?", "Nueva Venta", JOptionPane.YES_NO_OPTION);
            if (r != JOptionPane.YES_OPTION) return;
        }
        limpiarVenta();
    }//GEN-LAST:event_btnNuevaVentaActionPerformed

    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
     if (ventaActual == null || modelo.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "Agregue al menos un producto");
        return;
        }

    int ok = JOptionPane.showConfirmDialog(
            this,
            "¿Confirmar venta por S/. "
            + String.format("%.2f", ventaActual.getTotal()) + "?",
            "Confirmar",
            JOptionPane.YES_NO_OPTION);

    if (ok != JOptionPane.YES_OPTION)
        return;

    

    gestorVentas.registrarVenta(ventaActual);

    JOptionPane.showMessageDialog(
            this,
            "Venta N° " + ventaActual.getIdVenta()
            + " registrada.\nTotal: S/. "
            + String.format("%.2f", ventaActual.getTotal()));

    limpiarVenta();
    }//GEN-LAST:event_btnConfirmarActionPerformed
  private void limpiarVenta() {
        ventaActual = null;
        txtIdCliente.setText("");
        lblClienteInfo.setText("—");
        txtIdProducto.setText("");
        txtCantidad.setText("");
        lblProductoInfo.setText("—");
        modelo.setRowCount(0);
        lblTotal.setText("TOTAL:  S/. 0.00");
        txtIdVenta.setText(
        String.valueOf(
                gestorVentas.obtenerSiguienteIdVenta()));
       
    }

