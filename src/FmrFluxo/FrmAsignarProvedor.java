    private void cargarAsignaciones(){

    modeloAsignados.setRowCount(0);

    for(Proveedor p : gestorProveedor.getProveedores()){

        for(Producto prod : p.getProductos()){

            modeloAsignados.addRow(new Object[]{

                p.getIdProveedor(),
                p.getNombre(),
                p.getTelefono(),
                prod.getCodigo()+" - "+
                prod.getMarca()+" "+
                prod.getModelo()

            });

        }

    }

}
    private void cargarProductos() {
        cmbProducto.removeAllItems();
        for (Producto p : gestorInventario.getProductos()) {
            cmbProducto.addItem(p.getCodigo() + " - "
                + p.getMarca() + " " + p.getModelo());
        }
    }

    private void cargarProveedores() {
        cmbProveedor.removeAllItems();
        for (Proveedor p : gestorProveedor.getProveedores()) {
            cmbProveedor.addItem(p.getIdProveedor() + " - " + p.getNombre());
        }
    }

    private Producto getProductoSeleccionado() {
        int idx = cmbProducto.getSelectedIndex();
        if (idx < 0) return null;
        return gestorInventario.getProductos().get(idx);
    }

    private Proveedor getProveedorSeleccionado() {
        int idx = cmbProveedor.getSelectedIndex();
        if (idx < 0) return null;
        return gestorProveedor.getProveedores().get(idx);
    }

