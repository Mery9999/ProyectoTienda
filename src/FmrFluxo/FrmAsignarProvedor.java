    private void btnAsignarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAsignarActionPerformed
        // TODO add your handling code here:
    

    Producto producto = getProductoSeleccionado();
    Proveedor proveedor = getProveedorSeleccionado();

    if(producto == null || proveedor == null){
        JOptionPane.showMessageDialog(this,
                "Seleccione un producto y un proveedor");
        return;
    }

    // Verificar si ya existe en la BD
    if(gestorProveedor.existeAsignacion(
            proveedor.getIdProveedor(),
            producto.getIdProducto())){

        JOptionPane.showMessageDialog(this,
                "Este proveedor ya está asignado a este producto");
        return;
    }

    if(gestorProveedor.asignarProducto(
            proveedor.getIdProveedor(),
            producto.getIdProducto())){

        JOptionPane.showMessageDialog(this,
                "Proveedor asignado correctamente");

        cargarAsignaciones();

    }else{

        JOptionPane.showMessageDialog(this,
                "No se pudo realizar la asignación");
    }


    }//GEN-LAST:event_btnAsignarActionPerformed

