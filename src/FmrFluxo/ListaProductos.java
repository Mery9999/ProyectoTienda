    /** Vuelve a leer todos los productos del gestor y los pinta en la tabla. */
    public void cargarProductos() {

        modeloLista.setRowCount(0);

        ArrayList<Producto> productos = gestor.getProductos();

        for (Producto p : productos) {

            modeloLista.addRow(new Object[]{
                p.getIdProducto(),
                p.getCodigo(),
                p.getMarca(),
                p.getModelo(),
                p.getColor(),
                p.getCategoria(),
                p.getPrecio(),
                p.getStock()
            });
        }

        lblTotal.setText("Total de productos: " + gestor.cantidadProductos());
    }


