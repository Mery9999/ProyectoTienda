    private void cargarClientes() {

       modeloC.setRowCount(0);

    ArrayList<Cliente> clientes = gestor.listarClientes();

    for (Cliente c : clientes) {

        String documento;
        String tipo;

        if (c instanceof ClienteNatural) {

            documento = ((ClienteNatural) c).getDni();
            tipo = "Natural";

        } else {

            documento = ((Clientejuridico) c).getRuc();
            tipo = "Jurídico";
        }

        modeloC.addRow(new Object[]{
            c.getIdcliente(),
            tipo,
            c.getNombre(),
            documento,
            
            c.getTelefono(),
            c.getEmail()
        });

    }
        }

