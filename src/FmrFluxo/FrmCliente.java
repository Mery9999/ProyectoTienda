    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
            try {

           String nombre = txtNombre.getText().trim();
           String telefono = txtTelefono.getText().trim();
           String email = txtEmail.getText().trim();

           boolean esNatural =
                   cmbTipoCliente.getSelectedItem().toString().equals("Natural");

           if (nombre.isEmpty() || telefono.isEmpty() || email.isEmpty()) {

               JOptionPane.showMessageDialog(this,
                       "Complete nombre, teléfono y email");
               return;
           }

           int id = contadorId;

           Cliente cliente;

           if (esNatural) {

               String dni = txtDni.getText().trim();

               if (dni.isEmpty()) {
                   JOptionPane.showMessageDialog(this,
                           "Ingrese el DNI del cliente");
                   return;
               }

               if (!dni.matches("\\d{8}")) {
                   JOptionPane.showMessageDialog(this,
                           "El DNI debe tener 8 dígitos");
                   return;
               }

               cliente = new ClienteNatural(
                       id,
                       nombre,
                       telefono,
                       email,
                       dni);

           } else {

               String ruc = txtRuc.getText().trim();
               String razonSocial = txtRazonSocial.getText().trim();

               if (ruc.isEmpty() || razonSocial.isEmpty()) {
                   JOptionPane.showMessageDialog(this,
                           "Ingrese RUC y Razón Social");
                   return;
               }

               if (!ruc.matches("\\d{11}")) {
                   JOptionPane.showMessageDialog(this,
                           "El RUC debe tener 11 dígitos");
                   return;
               }

               cliente = new Clientejuridico(
                       id,
                       nombre,
                       telefono,
                       email,
                       ruc,
                       razonSocial);
           }

           if (gestor.registrarCliente(cliente)) {

               JOptionPane.showMessageDialog(this,
                       "Cliente registrado correctamente");

               cargarClientes();

               contadorId = gestor.obtenerSiguienteId();
               txtIdCliente.setText(String.valueOf(contadorId));

               btnLimpiarActionPerformed(null);

           } else {

               JOptionPane.showMessageDialog(this,
                       "No se pudo registrar el cliente");
           }

       } catch (Exception e) {

           JOptionPane.showMessageDialog(this,
                   "Error: " + e.getMessage());
       }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
    try {

        int id = Integer.parseInt(txtIdCliente.getText());

        Cliente cliente;

        if (cmbTipoCliente.getSelectedItem().toString().equals("Natural")) {

            cliente = new ClienteNatural(
                    id,
                    txtNombre.getText(),
                    txtTelefono.getText(),
                    txtEmail.getText(),
                    txtDni.getText());

        } else {

            cliente = new Clientejuridico(
                    id,
                    txtNombre.getText(),
                    txtTelefono.getText(),
                    txtEmail.getText(),
                    txtRuc.getText(),
                    txtRazonSocial.getText());
        }

        if (gestor.modificarCliente(cliente)) {

            JOptionPane.showMessageDialog(this,
                    "Cliente actualizado correctamente");

            cargarClientes();

            limpiarCampos();

        } else {

            JOptionPane.showMessageDialog(this,
                    "No se pudo actualizar");

        }

    } catch (Exception ex) {

        JOptionPane.showMessageDialog(this,
                "Error al modificar");
    }
    


    }//GEN-LAST:event_btnEditarActionPerformed

