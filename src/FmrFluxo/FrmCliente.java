    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:}
     

    String documento = txtBuscar.getText().trim();

    if (documento.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Ingrese un DNI o un RUC");

        return;
    }

    Cliente cliente = gestor.buscarCliente(documento);

    if (cliente == null) {

        JOptionPane.showMessageDialog(this,
                "Cliente no encontrado");

        return;
    }

    txtIdCliente.setText(String.valueOf(cliente.getIdcliente()));
    txtNombre.setText(cliente.getNombre());
    txtTelefono.setText(cliente.getTelefono());
    txtEmail.setText(cliente.getEmail());

    if (cliente instanceof ClienteNatural) {

        ClienteNatural cn = (ClienteNatural) cliente;

        cmbTipoCliente.setSelectedItem("Natural");
        txtDni.setText(cn.getDni());

        txtRuc.setText("");
        txtRazonSocial.setText("");

    } else {

        Clientejuridico cj = (Clientejuridico) cliente;

        cmbTipoCliente.setSelectedItem("Jurídico");
        txtRuc.setText(cj.getRuc());
        txtRazonSocial.setText(cj.getRazonSocial());

        txtDni.setText("");
    }

    }//GEN-LAST:event_btnBuscarActionPerformed
    
    private void limpiarCampos() {

    txtNombre.setText("");
    txtTelefono.setText("");
    txtEmail.setText("");
    txtDni.setText("");
    txtRuc.setText("");
    txtRazonSocial.setText("");

    contadorId = gestor.obtenerSiguienteId();
    txtIdCliente.setText(String.valueOf(contadorId));

    cmbTipoCliente.setSelectedIndex(0);
}

