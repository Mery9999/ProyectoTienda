    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        if (ventaSeleccionada == null) { JOptionPane.showMessageDialog(this, "Primero busque una venta"); return; }
        String tipo = cmbTipo.getSelectedItem().toString();
        if (tipo.equals("Factura") && !(ventaSeleccionada.getCliente() instanceof Clientejuridico)) {
            JOptionPane.showMessageDialog(this, "La Factura solo es para clientes con RUC.\nEmita una Boleta para este cliente."); return;
        }
        String numeroComp = tipo.equals("Boleta")
        ? "B001-" + String.format("%06d", contadorComprobante)
        : "F001-" + String.format("%06d", contadorComprobante);
        Comprobante comp = tipo.equals("Boleta") ? new Boleta(numeroComp, ventaSeleccionada) : new Factura(numeroComp, ventaSeleccionada);
        comp.generarComprobante();
        StringBuilder sb = new StringBuilder();
        sb.append("  ┌──────────────────────────────────────────┐\n");
        sb.append(tipo.equals("Boleta") ? "  │            BOLETA DE VENTA               │\n" : "  │            FACTURA DE VENTA              │\n");
        sb.append("  │               FLUXO                      │\n");
        sb.append("  └──────────────────────────────────────────┘\n\n");
        sb.append("  N° Comprobante: ").append(numeroComp).append("\n");
        sb.append("  Cliente: ").append(ventaSeleccionada.getCliente().mostrarDatos()).append("\n");
        sb.append("  ──────────────────────────────────────────\n  DETALLE:\n");
        for (DetalleVenta d : ventaSeleccionada.getDetalles())
        sb.append("    ").append(d.getProducto().getMarca()).append(" ").append(d.getProducto().getModelo()).append("  x").append(d.getCantidad()).append("  @S/. ").append(String.format("%.2f", d.getProducto().getPrecio())).append("  =  S/. ").append(String.format("%.2f", d.getSubtotal())).append("\n");
        sb.append("  ──────────────────────────────────────────\n");
        sb.append("  TOTAL:  S/. ").append(String.format("%.2f", ventaSeleccionada.getTotal())).append("\n\n  ¡Gracias por su compra!\n");
        txtAreaComprobante.setText(sb.toString());
        contadorComprobante++;
        JOptionPane.showMessageDialog(this, tipo + " " + numeroComp + " generada.\nTotal: S/. " + String.format("%.2f", ventaSeleccionada.getTotal()), "Comprobante Generado", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnGenerarActionPerformed


