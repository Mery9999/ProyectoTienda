    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tblProveedores.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                "Seleccione un proveedor de la tabla para eliminar");
            return;
        }

        int id = Integer.parseInt(modelo.getValueAt(fila, 0).toString());
        String nombre = modelo.getValueAt(fila, 1).toString();

        int confirmacion = JOptionPane.showConfirmDialog(this,
            "¿Está seguro de eliminar al proveedor \"" + nombre + "\"?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION);

        if (confirmacion != JOptionPane.YES_OPTION) return;

        gestor.eliminarProveedor(id);
        modelo.removeRow(fila);
        if(gestor.eliminarProveedor(id)){

            JOptionPane.showMessageDialog(this,"Proveedor eliminado");

            cargarTabla();

            txtId.setText(String.valueOf(gestor.obtenerSiguienteId()));

        }

        JOptionPane.showMessageDialog(this, "Proveedor eliminado correctamente");
        txtNombre.setText("");
        txtTelefono.setText("");
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        if(txtNombre.getText().trim().isEmpty() ||
       txtTelefono.getText().trim().isEmpty()){

        JOptionPane.showMessageDialog(this,"Complete todos los campos");
        return;
    }

    int id = Integer.parseInt(txtId.getText());

    Proveedor p = new Proveedor(
            id,
            txtNombre.getText().trim(),
            txtTelefono.getText().trim()
    );

    if(gestor.modificarProveedor(p)){

        JOptionPane.showMessageDialog(this,"Proveedor actualizado");

        cargarTabla();
        txtNombre.setText("");
        txtTelefono.setText("");
        txtId.setText(String.valueOf(gestor.obtenerSiguienteId()));

    }else{

        JOptionPane.showMessageDialog(this,"No se pudo actualizar");

    }
    }//GEN-LAST:event_btnEditarActionPerformed

