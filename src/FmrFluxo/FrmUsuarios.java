    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        
    if (txtUsuario.getText().trim().isEmpty()
            || txtPassword.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Complete todos los campos");
        return;
    }

    int id = Integer.parseInt(txtId.getText());

    String usuario = txtUsuario.getText().trim();
    String password = txtPassword.getText().trim();
    String rol = cmbRol.getSelectedItem().toString();

    Usuario nuevoUsuario = null;

    switch (rol) {

        case "Administrador":
            nuevoUsuario = new Administrador(
                    id,
                    usuario,
                    password);
            break;

        case "ATC":
            nuevoUsuario = new Atc(
                    id,
                    usuario,
                    password);
            break;

        case "Encargado Almacen":
            nuevoUsuario = new Encargadoalmacen(
                    id,
                    usuario,
                    password);
            break;
    }

    if (nuevoUsuario == null) {
        JOptionPane.showMessageDialog(this,
                "Rol no válido");
        return;
    }

    boolean registrado =
            gestor.registrarUsuario(nuevoUsuario, rol);

    if (registrado) {

        JOptionPane.showMessageDialog(this,
                "Usuario registrado correctamente");

        cargarUsuarios();

        contadorId++;

        txtId.setText(String.valueOf(contadorId));

        txtUsuario.setText("");
        txtPassword.setText("");
        cmbRol.setSelectedIndex(0);
        chkActivo.setSelected(true);

    } else {

        JOptionPane.showMessageDialog(this,
                "No se pudo registrar el usuario");

    }
    
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
            try {

            int id = Integer.parseInt(txtId.getText());

            Usuario u = gestor.buscarUsuario(id);

            if (u == null) {

                JOptionPane.showMessageDialog(this,
                        "Usuario no encontrado");

                return;
            }

                txtUsuario.setText(u.getUsername());
                txtPassword.setText(u.getPassword());

                chkActivo.setSelected(u.isActivo());
                
                if (u instanceof Administrador) {
                    cmbRol.setSelectedItem("Administrador");
                }
                else if (u instanceof Atc) {
                    cmbRol.setSelectedItem("ATC");
                }
                else if (u instanceof Encargadoalmacen) {
                    cmbRol.setSelectedItem("Encargado Almacen");
                }
            
                JOptionPane.showMessageDialog(this,
                    "Usuario encontrado");

            } catch (Exception e) {

                JOptionPane.showMessageDialog(this,
                    "Ingrese un ID válido");

            }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnDesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesactivarActionPerformed
        // TODO add your handling code here:
        try {

        int id = Integer.parseInt(txtId.getText());

        int opcion = JOptionPane.showConfirmDialog(
                this,
                "¿Desea desactivar este usuario?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION);

        if (opcion == JOptionPane.YES_OPTION) {

            boolean desactivado = gestor.desactivarUsuario(id);

            if (desactivado) {

                JOptionPane.showMessageDialog(this,
                        "Usuario desactivado correctamente");

                cargarUsuarios();

                txtUsuario.setText("");
                txtPassword.setText("");
                cmbRol.setSelectedIndex(0);
                chkActivo.setSelected(false);

            } else {

                JOptionPane.showMessageDialog(this,
                        "No se pudo desactivar el usuario");
            }
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Ingrese un ID válido");
    }
    }//GEN-LAST:event_btnDesactivarActionPerformed

