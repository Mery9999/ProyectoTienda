    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        try {

            int id = Integer.parseInt(txtIdProducto.getText());

            Producto p = gestor.buscarProducto(id);

            if (p == null) {

                JOptionPane.showMessageDialog(this,
                        "Producto no encontrado");
                return;
            }

            txtCodigo.setText(p.getCodigo());
            txtMarca.setText(p.getMarca());
            txtModelo.setText(p.getModelo());
            txtColor.setText(p.getColor());
            txtCategoria.setText(p.getCategoria());
            txtPrecio.setText(String.valueOf(p.getPrecio()));
            txtStock.setText(String.valueOf(p.getStock()));

            JOptionPane.showMessageDialog(this,
                    "Producto encontrado");

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Ingrese un ID válido");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        try {

            if (txtCodigo.getText().trim().isEmpty()
                    || txtMarca.getText().trim().isEmpty()
                    || txtModelo.getText().trim().isEmpty()
                    || txtColor.getText().trim().isEmpty()
                    || txtCategoria.getText().trim().isEmpty()
                    || txtPrecio.getText().trim().isEmpty()
                    || txtStock.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(this,
                        "Complete todos los campos");
                return;
            }

            int id = Integer.parseInt(txtIdProducto.getText());
            
            if (gestor.buscarProducto(id) != null) {
                JOptionPane.showMessageDialog(this, "Ya existe un producto con ese ID");
                return;
            }
            
            if (gestor.existeCodigo(txtCodigo.getText().trim())) {
                JOptionPane.showMessageDialog(this, "Ya existe un producto con ese codigo");
                return;
            }

            Producto p = new Producto(
                    id,
                    txtCodigo.getText(),
                    txtMarca.getText(),
                    txtModelo.getText(),
                    txtColor.getText(),
                    txtCategoria.getText(),
                    Double.parseDouble(txtPrecio.getText()),
                    Integer.parseInt(txtStock.getText())
            );

            gestor.registrarProducto(p);

            modeloP.addRow(new Object[]{
                p.getIdProducto(),
                p.getCodigo(),
                p.getMarca(),
                p.getModelo(),
                p.getColor(),
                p.getCategoria(),
                p.getPrecio(),
                p.getStock()
            });

            JOptionPane.showMessageDialog(this,
                    "Producto registrado correctamente");

            btnLimpiarActionPerformed(null);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Datos inválidos");
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
         try {

            int id = Integer.parseInt(txtIdProducto.getText());

            if (gestor.existeCodigoOtroProducto(
                    txtCodigo.getText().trim(), id)) {

                JOptionPane.showMessageDialog(this,
                        "El código ya pertenece a otro producto");
                return;
            }

            Producto p = new Producto(
                    id,
                    txtCodigo.getText(),
                    txtMarca.getText(),
                    txtModelo.getText(),
                    txtColor.getText(),
                    txtCategoria.getText(),
                    Double.parseDouble(txtPrecio.getText()),
                    Integer.parseInt(txtStock.getText())
            );

            boolean modificado = gestor.modificarProducto(p);

            if (modificado) {

                for (int i = 0; i < modeloP.getRowCount(); i++) {

                    if (Integer.parseInt(
                            modeloP.getValueAt(i, 0).toString()) == id) {

                        modeloP.setValueAt(p.getCodigo(), i, 1);
                        modeloP.setValueAt(p.getMarca(), i, 2);
                        modeloP.setValueAt(p.getModelo(), i, 3);
                        modeloP.setValueAt(p.getColor(), i, 4);
                        modeloP.setValueAt(p.getCategoria(), i, 5);
                        modeloP.setValueAt(p.getPrecio(), i, 6);
                        modeloP.setValueAt(p.getStock(), i, 7);

                        break;
                    }
                }

                JOptionPane.showMessageDialog(this,
                        "Producto modificado correctamente");

            } else {

                JOptionPane.showMessageDialog(this,
                        "Producto no encontrado");
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Datos inválidos");
        }
    }//GEN-LAST:event_btnModificarActionPerformed


